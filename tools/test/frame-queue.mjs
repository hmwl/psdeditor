import assert from 'node:assert/strict';
import { createFrameQueue } from '../../core/render/frame-queue.js';
const tick = async () => { await Promise.resolve(); await Promise.resolve(); };
const fence = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
const callbacks = new Map(); let timer = 0;
const schedule = cb => { callbacks.set(++timer, cb); return timer; }, unschedule = id => callbacks.delete(id);
const frame = () => { for (const [id, cb] of [...callbacks]) { callbacks.delete(id); cb(); } };
const seen = [], work = []; let current = 'a';
const queue = createFrameQueue({ schedule, unschedule, isCurrent: p => p.doc === current, submit(p){ seen.push(p.value); const f = fence(); work.push(f); return f.promise; } });
assert.equal(queue.request({ doc: 'a', value: 0 }), true);
queue.request({ doc: 'a', value: 1 }); frame();
for (let i = 2; i < 100; i++) queue.request({ doc: 'a', value: i });
assert.deepEqual(seen, [0, 1]); assert.equal(queue.stats.inFlight, 2); assert.equal(queue.stats.pending, true);
frame(); 
work[0].resolve(); await tick();
assert.deepEqual(seen, [0, 1, 99]); assert.equal(queue.stats.inFlight, 2);
work[1].resolve(); work[2].resolve(); await queue.flush();
assert.equal(queue.stats.lastCompleted, 100); assert.equal(queue.stats.coalesced, 97);
assert.equal(queue.stats.maxObservedInFlight, 2); assert.equal(queue.busy, false);

queue.request({ doc: 'a', value: 100 }); frame(); queue.request({ doc: 'a', value: 101 });
current = 'b'; frame(); assert.deepEqual(seen, [0, 1, 99, 100]);
queue.request({ doc: 'b', value: 102 });
work[3].resolve(); await tick(); assert.equal(seen.at(-1), 102);
work[4].resolve(); await queue.flush();

const background = fence(); const readback = queue.background(() => background.promise);
assert.ok(readback); assert.equal(queue.background(() => Promise.resolve()), null);
queue.request({ doc: 'b', value: 103 }); frame();
queue.request({ doc: 'b', value: 104 }); assert.equal(queue.stats.inFlight, 2);
background.resolve('pixels'); assert.equal(await readback, 'pixels'); await tick();
frame();
assert.equal(seen.at(-1), 104); work[5].resolve(); work[6].resolve(); await queue.flush();
assert.equal(queue.stats.backgroundSubmitted, 1);

queue.request({ doc: 'b', value: 105 }); frame(); queue.request({ doc: 'b', value: 106 });
queue.cancel(); work[7].resolve(); await queue.flush(); frame(); assert.notEqual(seen.at(-1), 106);
queue.dispose(); assert.equal(queue.request({ doc: 'b', value: 107 }), false); await queue.flush();

const broken = fence(), errors = [];
const bad = createFrameQueue({ schedule, unschedule, submit: () => broken.promise, onError: e => errors.push(e.message) });
bad.request(0); bad.request(1); const failed = assert.rejects(bad.flush(), /lost/); broken.reject(new Error('lost')); await failed;
assert.deepEqual(errors, ['lost']); assert.equal(bad.stats.pending, false); assert.equal(bad.request(2), false);
const throwing = createFrameQueue({ submit(){ throw new Error('encode'); }, onError: e => errors.push(e.message), schedule, unschedule });
assert.equal(throwing.request(0), false); await assert.rejects(throwing.flush(), /encode/);
const oneWork = [], oneSeen = [];
const one = createFrameQueue({ maxInFlight: 1, schedule, unschedule, submit(p){ const f = fence(); oneWork.push(f); oneSeen.push(p); return f.promise; } });
one.request(0); for (let i = 1; i <= 100; i++) one.request(i); frame();
assert.deepEqual(oneSeen, [0]); oneWork[0].resolve(); await tick(); assert.deepEqual(oneSeen, [0, 100]);
oneWork[1].resolve(); await one.flush(); assert.equal(one.stats.maxObservedInFlight, 1);
const layout = createFrameQueue({ schedule, unschedule, submit: () => null });
assert.equal(layout.request(0), true); await layout.flush(); assert.equal(layout.stats.skipped, 1); assert.equal(layout.stats.submitted, 0);
const predicate = createFrameQueue({ schedule, unschedule, submit: () => null, isCurrent(){ throw new Error('context'); } });
assert.equal(predicate.request(0), false); await assert.rejects(predicate.flush(), /context/);
const fastSeen = [];
const fast = createFrameQueue({ schedule, unschedule, submit(p){ fastSeen.push(p); return Promise.resolve(); } });
fast.request(0); await tick(); fast.request(1); fast.request(2); fast.request(3); await tick();
assert.deepEqual(fastSeen, [0]); frame(); await tick(); assert.deepEqual(fastSeen, [0, 3]);
fast.request(4); await fast.flush(); assert.deepEqual(fastSeen, [0, 3, 4]);
const bgWork = fence(), bgSeen = [];
const bg = createFrameQueue({ maxInFlight: 1, schedule, unschedule, submit(p){ bgSeen.push(p); return bgWork.promise; } });
const rejectedRead = bg.background(() => { throw new Error('readback'); }); bg.request('latest');
await assert.rejects(rejectedRead, /readback/); await tick(); assert.deepEqual(bgSeen, ['latest']);
bgWork.resolve(); await bg.flush(); assert.equal(bg.stats.failed, false);
const disposeWork = fence(), disposeSeen = [];
const disposing = createFrameQueue({ schedule, unschedule, submit(p){ disposeSeen.push(p); return disposeWork.promise; } });
disposing.request(0); disposing.request(1); const waiting = disposing.flush(); disposing.dispose(); await waiting;
assert.equal(disposing.request(2), false); disposeWork.resolve(); await tick(); assert.deepEqual(disposeSeen, [0, 1]);
