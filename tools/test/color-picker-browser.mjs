import assert from 'node:assert/strict';
import { loadPlaywright } from './pw.mjs';
const PW = await loadPlaywright();
const browser = await PW.chromium.launch({ executablePath: process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(`http://127.0.0.1:${process.argv[2]}/editor`);
  await page.waitForFunction(() => window.__psd_editor?.state, null, { timeout: 60000 });
  const initial = await page.evaluate(async () => {
    const sec = document.querySelector('#panelColor'), col = sec.closest('.panel-col');
    const group = sec.closest('.panel-group'); group.style.height = ''; group.style.flex = '';
    const sizes = [];
    for (const width of [260, 360, 280]) {
      col.style.width = width + 'px'; col.style.minWidth = width + 'px';
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
      const r = sec.querySelector('.cp2-field').getBoundingClientRect(); sizes.push([r.width, r.height]);
    }
    return sizes;
  });
  assert.equal(initial[0][1], initial[1][1], JSON.stringify(initial));
  assert.equal(initial[0][1], initial[2][1]); assert.ok(initial[1][0] > initial[0][0]);
  console.log('✓ default workspace width resize keeps field height independent');
  await page.evaluate(async () => { (await import('/editor/app/40-options-bar-wiring.js')).pickColor('bg'); });
  const picker = page.locator('.ps-color-picker');
  await picker.waitFor();
  assert.equal(await picker.locator('header').textContent(), '拾色器（背景色）');
  await page.screenshot({ path: '/tmp/psd_editor-color-picker.png' });
  const before = await picker.boundingBox(), header = await picker.locator('header').boundingBox();
  await page.mouse.move(header.x + 100, header.y + 12);
  await page.mouse.down(); await page.mouse.move(header.x + 180, header.y + 62, { steps: 5 }); await page.mouse.up();
  const moved = await picker.boundingBox();
  assert.ok(Math.abs(moved.x - before.x - 80) < 2);
  assert.ok(Math.abs(moved.y - before.y - 50) < 2);
  await page.mouse.move(moved.x + 100, moved.y + 12); await page.mouse.down();
  await page.mouse.move(-100, -100); await page.mouse.up();
  const clamped = await picker.boundingBox(); assert.ok(clamped.x >= 0 && clamped.y >= 0);
  console.log('✓ title bar drags the picker and clamps it inside the viewport');

  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('ff0000');
  assert.equal(await picker.locator('[data-channel="R"]').inputValue(), '255');
  assert.equal(await picker.locator('[data-channel="G"]').inputValue(), '0');
  await picker.getByRole('button', { name: '取消', exact: true }).click();
  await page.evaluate(async () => { (await import('/editor/app/40-options-bar-wiring.js')).pickColor('bg'); });
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), 'ffffff');
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('336699');
  await picker.getByRole('button', { name: '确定', exact: true }).click();
  await page.evaluate(async () => { (await import('/editor/app/40-options-bar-wiring.js')).pickColor('bg'); });
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), '336699');
  await page.keyboard.press('Escape');
  console.log('✓ foreground/background API titles, confirm, cancel and Escape');
  await page.evaluate(() => {
    window.colorEvents = [];
    const input = document.getElementById('txColor');
    input.oninput = () => window.colorEvents.push('input'); input.onchange = () => window.colorEvents.push('change');
    input.click();
  });
  assert.equal(await picker.locator('header').textContent(), '拾色器（文字颜色）');
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('112233');
  await page.keyboard.press('Enter');
  assert.deepEqual(await page.evaluate(() => [document.getElementById('txColor').value, window.colorEvents]), ['#112233', ['input', 'change']]);
  console.log('✓ existing native color input is intercepted and committed once');
  await page.evaluate(async () => {
    const { formDialog } = await import('/editor/dialog.js');
    window.parentResult = formDialog('测试设置', [{ key: 'color', label: '覆盖颜色', type: 'color', value: '#abcdef' }]);
  });
  await page.locator('dialog[open] input[type=color]').click();
  assert.equal(await picker.locator('header').textContent(), '拾色器（覆盖颜色）');
  await picker.locator('[data-channel="H"]').fill('120');
  await picker.locator('[data-channel="S"]').fill('100');
  await picker.locator('[data-channel="B"]').fill('100');
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), '00ff00');
  await picker.locator('[data-channel="L"]').fill('50');
  assert.ok(Number(await picker.locator('[data-channel="R"]').inputValue()) <= 255);
  for (const axis of ['R', 'L', 'S', 'H']) await picker.locator(`input[type=radio][value="${axis}"]`).check();
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('123456');
  await picker.getByLabel('只有 Web 颜色').check();
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), '003366');
  await picker.getByRole('button', { name: '添加到色板', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.pcp-message')?.textContent === '已添加到色板');
  await picker.getByRole('button', { name: '颜色库', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.pcb-color[aria-selected=true]'));
  assert.equal(await picker.locator('header').textContent(), '颜色库');
  assert.equal(await picker.locator('.pcb-select option').count(), 12);
  await picker.getByRole('textbox', { name: '查找色库颜色' }).fill('751-8');
  assert.equal(await picker.locator('.pcb-color[aria-selected=true]').getAttribute('aria-label'), 'ANPA 751-8 AdPro');
  assert.deepEqual(await picker.locator('.pcb-values > div').allTextContents(), ['L:　60', 'a:　15', 'b:　12']);
  const swatchSize = await picker.locator('.pcb-color[aria-selected=true] i').boundingBox();
  assert.ok(swatchSize.height > 20, 'book colors must be full swatches, not thin lines');
  await picker.getByRole('combobox', { name: '色库' }).selectOption({ label: 'HKS E 印刷色' });
  await page.waitForFunction(() => document.querySelector('.pcb-color[aria-selected=true]')?.getAttribute('aria-label')?.startsWith('HKS '));
  await picker.getByRole('combobox', { name: '色库' }).selectOption({ label: 'ANPA 颜色' });
  await page.waitForFunction(() => document.querySelector('.pcb-color[aria-selected=true]')?.getAttribute('aria-label')?.startsWith('ANPA '));
  await picker.getByRole('textbox', { name: '查找色库颜色' }).fill('751-8');
  await picker.screenshot({ path: '/tmp/psd_editor-color-books.png' });
  await picker.getByRole('button', { name: '下一页颜色', exact: true }).click();
  await picker.getByRole('button', { name: '上一页颜色', exact: true }).click();
  await picker.getByRole('button', { name: '拾色器', exact: true }).click();
  assert.equal(await picker.locator('header').textContent(), '拾色器（覆盖颜色）');
  assert.notEqual(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), '003366');
  await picker.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.locator('dialog[open] input[type=color]').inputValue(), '#abcdef');
  await page.keyboard.press('Escape');
  console.log('✓ nested dialogs, channel modes, web colors, swatches and color library');
  await page.evaluate(async () => { (await import('/editor/app/40-options-bar-wiring.js')).pickColor('fg'); await (await import('/editor/color-panel.js')).colorPanel.reloadProfiles(); });
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('00ff00');
  assert.equal(await picker.locator('.color-safety-print').isVisible(), true);
  const correction = await page.evaluate(async () => (await import('/editor/color-panel.js')).colorPanel._conv.nearestPrintable([0, 255, 0]));
  await picker.locator('.color-safety-print').click();
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), correction.map(v => v.toString(16).padStart(2, '0')).join(''));
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('123456');
  assert.equal(await picker.locator('.color-safety-web').isVisible(), true);
  await picker.locator('.color-safety-web').click();
  assert.equal(await picker.getByRole('textbox', { name: '十六进制颜色' }).inputValue(), '003366');
  assert.equal(await picker.locator('.color-safety-web').isVisible(), false);
  await picker.getByRole('textbox', { name: '十六进制颜色' }).fill('123456');
  await picker.getByRole('button', { name: '确定', exact: true }).click();
  await page.locator('.cp2-websafe').waitFor({ state: 'visible' });
  const warningLayout = await page.evaluate(() => {
    const b = document.querySelector('.cp2-websafe'), icon = b.firstElementChild.getBoundingClientRect(), chip = b.querySelector('i').getBoundingClientRect();
    return { right: chip.left > icon.left, sameRow: Math.abs(chip.top + chip.height / 2 - icon.top - icon.height / 2) < 1 };
  });
  assert.deepEqual(warningLayout, { right: true, sameRow: true });
  console.log('✓ print/web corrections and panel icon/chip horizontal layout');
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
