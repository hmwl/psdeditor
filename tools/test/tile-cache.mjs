import assert from 'node:assert/strict';
import { createTileCache, interleaveTileStreams, lazyTileState, planVisibleTiles } from '../../core/render/tile-cache.js';

const state = () => lazyTileState({ width: 2048, height: 2048 });
const tile = (x = 0, y = 0, size = 16) => ({ x, y, width: 2, height: size / 8, data: new Uint8ClampedArray(size) });
const a = state(), b = state(), c = state(), evicted = [];
const cache = createTileCache({ budget: 64, maxPerState: 3, onEvict: s => evicted.push(s) });
cache.put(a, '0:0', tile()); cache.put(b, '0:0', tile()); cache.put(c, '0:0', tile());
cache.get(a, '0:0'); cache.put(c, '2:0', tile(2)); cache.put(c, '4:0', tile(4));
assert.equal(b.tiles.size, 0, 'global LRU evicts across layers'); assert.equal(a.tiles.size, 1);
assert.equal(cache.stats.bytes, 64); assert.ok(evicted.includes(b));
cache.setWanted([{ state: a, key: '0:0' }]);
cache.put(c, '6:0', tile(6)); assert.equal(cache.stats.tiles, 4); assert.equal(c.tiles.size, 3);
cache.put(c, '8:0', tile(8)); assert.equal(c.tiles.size, 3); assert.ok(a.tiles.has('0:0'));
assert.ok(cache.stats.bytes <= cache.budget);
assert.equal(cache.put(b, 'stale', tile(), { wantedOnly: true }), false);
assert.equal(b.tiles.size, 0, 'completed stale jobs cannot fill the cache');
const version = a.version;
cache.clear(); assert.equal(cache.stats.bytes, 0); assert.equal(a.tiles.size + c.tiles.size, 0); assert.ok(a.version > version);

const layers = [a, b, c].map((s, index) => ({ state: s, index, cells: Array.from({ length: 10 }, (_, rank) => ({ key: `${rank}:0`, x: rank, y: 0, bytes: 16 })) }));
const plan = planVisibleTiles(layers, 64, 3);
assert.deepEqual(plan.cells.map(c => c.index), [0, 1, 2, 0]); assert.equal(plan.bytes, 64); assert.equal(plan.layers, 3);
cache.setWanted(plan.cells);
for (const c of plan.cells) assert.equal(cache.put(c.state, c.key, tile()), true);
assert.equal(cache.stats.bytes, 64);
for (let i = 0; i < 50; i++) for (const c of plan.cells) assert.ok(cache.get(c.state, c.key));
assert.equal(cache.stats.evictions, 7, 'revisiting the stable visible set does not evict/redecode it');
assert.equal(cache.put(a, '0:0', tile(0, 0, 32)), false, 'a larger pinned replacement must not overflow the real byte budget');
assert.equal(cache.stats.bytes, 64);
assert.equal(cache.put(b, 'oversized', tile(0, 0, 80)), false);
const edgePlan = planVisibleTiles([{ state: a, index: 0, cells: [{ key: '0:0', bytes: 60 }, { key: '2:0', bytes: 4 }] }, { state: b, index: 1, cells: [{ key: '0:0', bytes: 16 }] }], 64);
assert.equal(edgePlan.bytes, 64, 'use exact edge-tile bytes rather than assuming every cell is full');
assert.deepEqual(edgePlan.cells.map(c => c.key), ['0:0', '2:0']);
const streams = interleaveTileStreams([{ state: a, x: 0, y: 256 }, { state: b, x: 0, y: 128 }, { state: a, x: 256, y: 0 }, { state: b, x: 0, y: 0 }, { state: a, x: 0, y: 0 }]);
assert.deepEqual(streams.map(c => [c.state === a ? 'a' : 'b', c.x, c.y]), [['a', 0, 0], ['b', 0, 0], ['a', 256, 0], ['b', 0, 128], ['a', 0, 256]]);
cache.clear();
const closed = lazyTileState({ width: 256, height: 256 }, 11), open = lazyTileState({ width: 256, height: 256 }, 22);
cache.put(closed, '0:0', tile()); cache.put(open, '0:0', tile());
cache.setWanted([{ state: closed, key: '0:0' }, { state: open, key: '0:0' }]);
cache.releaseOwner(11); assert.equal(closed.tiles.size, 0); assert.equal(open.tiles.size, 1); assert.equal(cache.stats.wanted, 1);
assert.equal(cache.stats.bytes, 16); cache.clear();
console.log('✓ 跨层/跨文档字节预算、LRU、可见集公平分配、稳定驻留与过期结果拒绝');
